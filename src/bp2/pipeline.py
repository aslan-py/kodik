"""Конвейер очистки BP-2 (нормализация, дедупликация, фильтрация шума).

Шаги идут сверху вниз по потоку данных (см. ABOUT.md, раздел BP-2):

    получить raw_data по id → разбить на items[] → предочистка →
    нормализация (pydantic) → чёрные домены → стоп-слова →
    дедуп + запись (ON CONFLICT) → антишум (UPDATE по лимиту)

Между этапами передаётся id сырья, а не JSON: BP-2 сам читает raw_data
по id (отвязка от BP-1, можно переразобрать то же сырьё с новыми правилами).

Этот файл наполняется по шагам. Сейчас реализован входной блок:
загрузка снимка, разбиение на объекты и предочистка текстовых полей.
"""

import html
import re

from sqlalchemy.ext.asyncio import AsyncSession

from src.bp1.models import RawItem

# ============================================================================
#  Шаг 0 — предочистка (вспомогательная функция)
# ============================================================================

# Пробельные символы, которые парсеры притаскивают со страниц и которые
# обычный \s не всегда ловит: неразрывный пробел, узкий неразрывный,
# нулевой ширины. Приводим их к обычному пробелу перед схлопыванием.
_WHITESPACE_LOOKALIKES = {
    '\xa0': ' ',  # неразрывный пробел (&nbsp;)
    ' ': ' ',  # узкий неразрывный пробел
    '​': '',  # пробел нулевой ширины
    '﻿': '',  # BOM / zero-width no-break space
}
_WS_TABLE = str.maketrans(_WHITESPACE_LOOKALIKES)

# HTML-теги, которые остаются в сыром тексте после кривого парсинга
# (<p>, <br>, <b>…). Срезаем целиком, заменяя на пробел.
_HTML_TAG = re.compile(r'<[^>]+>')


def clean_text(value: object) -> str | None:
    """Предочистка одного текстового поля.

    Сырьё с веб-страниц приходит «грязным»: обрывки HTML-тегов,
    HTML-сущности (&nbsp;, &laquo;, &mdash;), неразрывные пробелы, табы
    и переводы строк. Приводим к чистому виду:

    1. срезаем HTML-теги (<p>, <b>, …);
    2. декодируем HTML-сущности (&nbsp; → пробел, &laquo; → «);
    3. «похожие на пробел» символы → обычный пробел;
    4. схлопываем пробелы/переводы строк в один и обрезаем края.

    Пустой результат (только пробелы / None) → None, чтобы в БД лежал
    честный NULL, а не строка из пробелов. Принимает object: в сыром
    JSON поле может быть числом или None.
    """
    if value is None:
        return None
    s = _HTML_TAG.sub(' ', str(value))
    s = html.unescape(s)
    s = s.translate(_WS_TABLE)
    s = re.sub(r'\s+', ' ', s).strip()
    return s or None


# ============================================================================
#  Шаг 1 — загрузка снимка по id
# ============================================================================


async def load_raw_item(
    session: AsyncSession,
    raw_item_id: int,
) -> RawItem | None:
    """Забрать снимок raw_item по id.

    Возвращает объект RawItem или None, если строки нет. Проверку статуса
    (new/changed/error) и наличие raw_data делает вызывающий код —
    здесь только достаём строку.
    """
    return await session.get(RawItem, raw_item_id)


# ============================================================================
#  Шаг 2 — разбить raw_data на отдельные объекты + предочистка
# ============================================================================


def split_items(raw_data: dict) -> list[dict]:
    """Разбить raw_data на список отдельных событий с предочисткой.

    raw_data устроен как {"meta": {...}, "items": [ {...}, ... ]}.
    На каждый объект из items[] переносим контекст из meta (конкурент,
    источник, триггер, id задачи) — дальше по конвейеру он нужен для
    lookup'ов и дедуп-ключа. Текстовые поля прогоняем через clean_text.

    Возвращает список плоских dict'ов (по одному на событие). Если items
    пуст или отсутствует — вернётся пустой список.
    """
    meta = raw_data.get('meta') or {}
    items = raw_data.get('items') or []

    result: list[dict] = []
    for item in items:
        result.append(
            {
                # --- контекст из meta (общий для всей выгрузки) ---
                'search_task_id': meta.get('search_task_id'),
                'source': clean_text(meta.get('source')),
                'competitor': clean_text(meta.get('competitor')),
                'trigger': clean_text(meta.get('trigger')),
                # --- поля самого события (предочищены) ---
                'url': clean_text(item.get('url')),
                'title': clean_text(item.get('title')),
                'text': clean_text(item.get('text')),
                'date': clean_text(item.get('date')),
                'region': clean_text(item.get('region')),
                'media': clean_text(item.get('media')),
                # extra — сырые источник-специфичные факты (у hh зарплата),
                # не чистим: это структура, разберём при нормализации.
                'extra': item.get('extra') or {},
            }
        )
    return result
