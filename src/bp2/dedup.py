"""Дедупликация событий BP-2: как мы решаем, что две новости — одна и та же.

Одна новость обычно приходит с нескольких сайтов (СМИ перепечатывают друг
друга). Хранить её копии в normalized_item не нужно — надо склеить в одну.

Считаем событие дубликатом другого, если совпадают ЧЕТЫРЕ бизнес-поля:
    competitor · заголовок · дата публикации · регион
Именно эти поля определяют «что за событие», а не «на каком сайте оно висит».
Домен/URL/СМИ намеренно НЕ участвуют — иначе перепечатки не склеятся.

Заголовок перед сравнением прогоняем через norm() — гасим регистр, пунктуацию
и лишние пробелы, чтобы «Бегемот открыл склад» и "бегемот, открыл склад!!!"
считались одним заголовком.

Из этих полей собираем строку и берём от неё sha256 — это и есть dedup_key.
Он лежит в normalized_item под UNIQUE-индексом: при вставке ON CONFLICT дубль
просто не создаётся. Одинаковый ключ = одно событие.

Функция живёт здесь (а не в seed-скриптах), чтобы и пайплайн, и сиды считали
ключ ОДНОЙ формулой — иначе одна новость получит разные ключи и не склеится.
"""

import hashlib
import re


def norm(s: str | None) -> str:
    """Нормализация строки для ключа: lower, без пунктуации, схлоп пробелов."""
    s = (s or '').lower()
    s = re.sub(r'[^\w\s]', '', s)
    return re.sub(r'\s+', ' ', s).strip()


def make_dedup_key(
    competitor: str | None,
    title: str | None,
    published: str | None,
    region: str | None,
) -> str:
    """sha256 бизнес-полей: у одной новости на разных сайтах ключ совпадает."""
    raw = f'{competitor or ""}|{norm(title)}|{published or ""}|{region or ""}'
    return hashlib.sha256(raw.encode()).hexdigest()
